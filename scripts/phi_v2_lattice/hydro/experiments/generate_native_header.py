"""Emit hydro_tables.h from channels.py: velocities, flags, relation targets, inverse sources, hashes."""
import hashlib
import sys
from pathlib import Path
from .. import channels as H, staged as P

ROOT = Path(__file__).resolve().parents[4]
OUT = ROOT / "engine" / "strict" / "hydro" / "hydro_tables.h"


def sources():
    """Inverse of relation_target: for each SC (axis) and FCC (plane, diag) relation owned by a
    site, the (offset, velocity) pairs of particles that propose onto it."""
    sc = {a: [] for a in range(3)}
    fcc = {(p, q): [] for p in range(3) for q in range(2)}
    for v in range(24):
        kind, offset, idx = H.relation_target(v)
        source_offset = tuple(-x for x in offset)      # particle sits at owner - offset
        (sc[idx[0]] if kind == "sc" else fcc[idx]).append((source_offset, v))
    assert all(len(sc[a]) == 4 for a in range(3)) and all(len(fcc[k]) == 2 for k in fcc)
    return sc, fcc


def _bytes_literal(name, hexdigest):
    return f"constexpr unsigned char {name}[32] = {{" + ", ".join(str(b) for b in bytes.fromhex(hexdigest)) + "};"


def emit():
    sc, fcc = sources()
    target = [H.relation_target(v) for v in range(24)]
    lines = ["// Generated by scripts/phi_v2_lattice/hydro/experiments/generate_native_header.py; do not edit.",
             "#pragma once", "#include <cstdint>", "namespace ftd::hydro::tables {",
             "constexpr int N_VEL = 24, N_PHASE = 4, N_POL = 2, N_CHANNELS = 192;",
             "constexpr std::int8_t VELOCITY[24][3] = {" + ", ".join("{%d,%d,%d}" % v for v in H.VELOCITIES) + "};",
             "constexpr bool IS_FACE[24] = {" + ", ".join("true" if f else "false" for f in H.IS_FACE) + "};",
             "constexpr std::int8_t TARGET_KIND[24] = {" + ", ".join("0" if t[0] == "sc" else "1" for t in target) + "};",
             "constexpr std::int8_t TARGET_OFFSET[24][3] = {" + ", ".join("{%d,%d,%d}" % t[1] for t in target) + "};",
             "constexpr std::int8_t TARGET_INDEX[24][2] = {" + ", ".join("{%d,%d}" % ((t[2] + (0,))[:2]) for t in target) + "};",
             "constexpr int SC_SOURCES = 4, FCC_SOURCES = 2;",
             "constexpr std::int8_t SOURCE_SC[3][4][4] = {" + ", ".join(
                 "{" + ", ".join("{%d,%d,%d,%d}" % (o + (v,)) for o, v in sc[a]) + "}" for a in range(3)) + "};",
             "constexpr std::int8_t SOURCE_FCC[3][2][2][4] = {" + ", ".join(
                 "{" + ", ".join("{" + ", ".join("{%d,%d,%d,%d}" % (o + (v,)) for o, v in fcc[(p, q)]) + "}"
                                 for q in range(2)) + "}" for p in range(3)) + "};",
             _bytes_literal("TABLE_HASH", H.TABLE_HASH), _bytes_literal("ENCODING_HASH", H.ENCODING_HASH),
             _bytes_literal("LAW_HASH", hashlib.sha256(P.LAW_ID.encode()).hexdigest()),
             f'constexpr const char* LAW_ID = "{P.LAW_ID}";', "}  // namespace ftd::hydro::tables", ""]
    return "\n".join(lines)


def main():
    text = emit()
    if "--check" in sys.argv:
        if not OUT.is_file() or OUT.read_text(encoding="utf-8") != text:
            raise SystemExit("hydro_tables.h is stale; regenerate")
        print("hydro_tables.h up to date")
        return
    OUT.write_text(text, encoding="utf-8")
    print(OUT)


if __name__ == "__main__":
    main()
