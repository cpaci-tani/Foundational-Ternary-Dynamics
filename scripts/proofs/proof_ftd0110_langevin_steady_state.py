def field_in_block(block_center, green_table):
    """27-vector of G_L evaluated at (block_center + delta) for delta in
    {-1,0,1}^3, indexed by VOXELS order.
    """
    cx, cy, cz = block_center
    field = np.zeros(N_VOXELS)
    for i, (dx, dy, dz) in enumerate(VOXELS):
        rx, ry, rz = cx + dx, cy + dy, cz + dz
        field[i] = green_table.get((rx, ry, rz), 0.0)
    return field


def slow_mode_energy_fraction(field, basis, L_27):
    """Fraction of |field|^2 carried by the slow mode of the trivial-
    irrep subspace.

    Returns:
        f_slow      = |<v_slow_local, field>|^2 / |field_in_subspace|^2
        d_G          = trivial-irrep dim
        slow_lambda = eigenvalue of slow mode
        f_block      = |field_in_subspace|^2 / |field|^2 (subspace fraction)
    """
    d = basis.shape[1]
    # Project field onto trivial subspace
    field_in_sub = basis.T @ field
    norm_sq_full = np.sum(field ** 2)
    norm_sq_in = np.sum(field_in_sub ** 2)
    f_block = norm_sq_in / norm_sq_full if norm_sq_full > 1e-14 else 0.0

    # Build trivial-subspace Laplacian
    M = basis.T @ L_27 @ basis
    M = 0.5 * (M + M.T)
    eigvals, eigvecs = np.linalg.eigh(M)
    # Slow mode: smallest |lambda|
    slow_idx = int(np.argmin(np.abs(eigvals)))
    slow_lambda = float(eigvals[slow_idx])
    # Project field-in-subspace onto eigenvector
    v_slow = eigvecs[:, slow_idx]
    proj_slow = float(np.dot(v_slow, field_in_sub))
    energy_slow = proj_slow ** 2

    f_slow = energy_slow / norm_sq_in if norm_sq_in > 1e-14 else 0.0
    return f_slow, d, slow_lambda, f_block


