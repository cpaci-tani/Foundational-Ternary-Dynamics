def perm_matrix(perm, sign):
    M = np.zeros((N_VOXELS, N_VOXELS))
    for j, v in enumerate(VOXELS):
        gv = tuple(sign[i] * v[perm[i]] for i in range(3))
        i = VOXEL_INDEX[gv]
        M[i, j] = 1.0
    return M


def trivial_basis(elements):
    P = np.zeros((N_VOXELS, N_VOXELS))
    for perm, sign in elements:
        P += perm_matrix(perm, sign)
    P /= len(elements)
    eigvals, eigvecs = np.linalg.eigh(P)
    mask = eigvals > 0.5
    return eigvecs[:, mask]


# ---------------------------------------------------------------------------
# Global lattice Poisson Green's function
# ---------------------------------------------------------------------------

def lattice_green_function_table(L_side, c=C_LAT, max_distance=20):
    """Compute G_L(r) for r = (rx, ry, rz) with |r|_inf <= max_distance.

    G_L solves c^2 * Delta_L G_L = -delta on the periodic L^3 lattice
    using the SC (simple cubic) Laplacian. Per FTD's Phase G convention.
    """
    table = {}
    # Compute via direct Fourier sum
    for rx in range(-max_distance, max_distance + 1):
        for ry in range(-max_distance, max_distance + 1):
            for rz in range(-max_distance, max_distance + 1):
                if abs(rx) > max_distance or abs(ry) > max_distance or abs(rz) > max_distance:
                    continue
                # Compute G_L at (rx, ry, rz) via Fourier sum
                total = 0.0
                for n1 in range(L_side):
                    for n2 in range(L_side):
                        for n3 in range(L_side):
                            if n1 == 0 and n2 == 0 and n3 == 0:
                                continue
                            k = (2 * math.pi * n1 / L_side,
                                 2 * math.pi * n2 / L_side,
                                 2 * math.pi * n3 / L_side)
                            kh2 = sum(4.0 * math.sin(0.5 * ki) ** 2 for ki in k)
                            if kh2 == 0:
                                continue
                            phase = math.cos(k[0]*rx + k[1]*ry + k[2]*rz)
                            total += phase / (c * c * kh2)
                table[(rx, ry, rz)] = total / (L_side ** 3)
    return table


def lattice_green_at_offset(rx, ry, rz, c=C_LAT, L_side=L_LATTICE):
    """Single-point evaluation of G_L."""
    total = 0.0
    for n1 in range(L_side):
        for n2 in range(L_side):
            for n3 in range(L_side):
                if n1 == 0 and n2 == 0 and n3 == 0:
                    continue
                k = (2 * math.pi * n1 / L_side,
                     2 * math.pi * n2 / L_side,
                     2 * math.pi * n3 / L_side)
                kh2 = sum(4.0 * math.sin(0.5 * ki) ** 2 for ki in k)
                if kh2 == 0:
                    continue
                phase = math.cos(k[0]*rx + k[1]*ry + k[2]*rz)
                total += phase / (c * c * kh2)
    return total / (L_side ** 3)


# Use numpy for vectorized speed
def green_table_vectorized(L_side, c=C_LAT, max_dist=12):
    """Faster computation using numpy."""
    L = L_side
    # Build k-vectors (excluding zero mode)
    n = np.arange(L)
    k1, k2, k3 = np.meshgrid(n, n, n, indexing='ij')
    k1f = 2 * np.pi * k1.flatten() / L
    k2f = 2 * np.pi * k2.flatten() / L
    k3f = 2 * np.pi * k3.flatten() / L
    # k_hat^2 = 4 sum sin(k/2)^2
    kh2 = 4 * (np.sin(0.5 * k1f) ** 2 + np.sin(0.5 * k2f) ** 2 + np.sin(0.5 * k3f) ** 2)
    nonzero = kh2 > 1e-14
    kh2 = kh2[nonzero]
    k1f = k1f[nonzero]
    k2f = k2f[nonzero]
    k3f = k3f[nonzero]
    inv_kh2 = 1.0 / (c * c * kh2)
    # For each r in the box, compute G_L(r)
    table = {}
    for rx in range(-max_dist, max_dist + 1):
        for ry in range(-max_dist, max_dist + 1):
            for rz in range(-max_dist, max_dist + 1):
                phase = np.cos(k1f * rx + k2f * ry + k3f * rz)
                table[(rx, ry, rz)] = float(np.sum(phase * inv_kh2)) / (L ** 3)
    return table


