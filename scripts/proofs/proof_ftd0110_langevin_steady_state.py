L_LATTICE = 32                  # global lattice size
C_LAT = 1.0 / math.sqrt(3.0)    # CFL speed of light


# ---------------------------------------------------------------------------
# Voxels of a 27-block (relative coordinates {-1, 0, 1}^3)
# ---------------------------------------------------------------------------

VOXELS = [tuple(d) for d in product(range(-1, 2), repeat=3)]
N_VOXELS = len(VOXELS)
VOXEL_INDEX = {v: i for i, v in enumerate(VOXELS)}
CENTER_INDEX = VOXEL_INDEX[(0, 0, 0)]


# ---------------------------------------------------------------------------
# 18-point Laplacian on the 27-voxel block (Phase A)
# ---------------------------------------------------------------------------

def build_laplacian_27():
    L = np.zeros((N_VOXELS, N_VOXELS))
    a_face = 1.0 / 3.0
    b_edge = 1.0 / 6.0
    for i, vi in enumerate(VOXELS):
        L[i, i] = -(6 * a_face + 12 * b_edge)
        for j, vj in enumerate(VOXELS):
            if i == j:
                continue
            d2 = sum((a - b) ** 2 for a, b in zip(vi, vj))
            if d2 == 1:
                L[i, j] = a_face
            elif d2 == 2:
                L[i, j] = b_edge
    return L


