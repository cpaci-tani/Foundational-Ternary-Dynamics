import sys
from mpmath import mp, mpf, mpc, gamma, sqrt, pi as mppi, exp, jtheta, zeta, agm, quad, pslq
import sympy as sp

mp.dps = 60
G = gamma(mpf(1)/4) / gamma(mpf(3)/4)
PI = +mppi
S = sqrt(G)                  # s = sqrt(G*)
W = PI ** (mpf(1)/4)         # w = pi^(1/4)
R4 = mpf(2) ** (mpf(1)/4)    # 2^(1/4)
DELTA = sqrt(G * (4*G - 1))
TOL = mpf(10) ** -48

checks = []
def check(name, ok, detail=""):
    checks.append((name, bool(ok)))
    print(("  [PASS] " if ok else "  [FAIL] ") + name + ((" -- " + detail) if detail else ""))

def close(a, b, tol=TOL):
    return abs(a - b) < tol

print("=" * 92)
print("FTD-0353: the valuation theorem at the prime (4G*-1) -- machine-checkable layer")
print("G*    = " + mp.nstr(G, 30))
print("delta = " + mp.nstr(DELTA, 30))
print("=" * 92)

# ---------------------------------------------------------------- A. setup
print("\nA. Setup identities")
check("A1 reflection: G* == Gamma(1/4)^2/(pi sqrt2)",
      close(G, gamma(mpf(1)/4)**2 / (PI*sqrt(mpf(2)))))
x_p = 8*G**2 + 4*G*DELTA
x_m = 8*G**2 - 4*G*DELTA
qp = (16*G**2 + sqrt((16*G**2)**2 - 4*16*G**3)) / 2
qm = (16*G**2 - sqrt((16*G**2)**2 - 4*16*G**3)) / 2
check("A2 x_pm = 8G*^2 +- 4G* delta match quadratic formula", close(x_p, qp) and close(x_m, qm))
check("A3 delta == (x_+ - x_-)/(8G*)  (sole root-distinguishing irrational)",
      close(DELTA, (x_p - x_m)/(8*G)))
check("A4 hull coordinate: Gamma(1/4) == s * w^2 * 2^(1/4)",
      close(gamma(mpf(1)/4), S * W**2 * R4))
check("A5 hull coordinate: Gamma(3/4) == w^2 * 2^(1/4) / s",
      close(gamma(mpf(3)/4), W**2 * R4 / S))
check("A6 F-membership: G* == s^2 and pi == w^4", close(G, S**2) and close(PI, W**4))

# ------------------------------------------------- B. inventory membership
print("\nB. Documented native analytic outputs are Qbar-monomials in (s, w)")
dz14 = sqrt(2*PI)/gamma(mpf(1)/4)     # det_zeta(D_{1/4}) = sqrt(2pi)/Gamma(1/4)  (Lerch, FTD-0234)
dz34 = sqrt(2*PI)/gamma(mpf(3)/4)
check("B1 det_zeta(D_{1/4}) == 2^(1/4) * s^(-1)", close(dz14, R4 / S))
check("B2 det_zeta(D_{3/4}) == 2^(1/4) * s", close(dz34, R4 * S))
check("B3 det_zeta ratio == G* == s^2  (FTD-0234)", close(dz34/dz14, S**2))
watson = G**2 / (2*PI)
check("B4 Watson G_BCC(0) = G*^2/(2pi) == s^4/(2 w^4)  (OT-2.1)",
      close(watson, S**4/(2*W**4)))
check("B5 Watson closed form G*^2/(2pi) == Gamma(1/4)^4/(4 pi^3)",
      close(watson, gamma(mpf(1)/4)**4/(4*PI**3)))
q_nome = exp(-PI)
t3 = jtheta(3, 0, q_nome); t2 = jtheta(2, 0, q_nome); t4 = jtheta(4, 0, q_nome)
check("B6 theta3(0, i) == pi^(1/4)/Gamma(3/4)  (FTD-0341 C2)",
      close(t3, W/gamma(mpf(3)/4), mpf(10)**-40))
check("B7 theta3 == s * 2^(-1/4) * w^(-1)  (hull monomial)",
      close(t3, S/(R4*W), mpf(10)**-40))
check("B8 theta2 == theta4 == s * 2^(-1/2) * w^(-1)  (self-dual point)",
      close(t2, t4, mpf(10)**-40) and close(t4, S/(sqrt(mpf(2))*W), mpf(10)**-40))
check("B9 theta3^2 == G*/sqrt(2 pi)  (the [2u] quadratic layer, sec. C)",
      close(t3**2, G/sqrt(2*PI), mpf(10)**-40))
eta14 = zeta(0, mpf(1)/4) - zeta(0, mpf(3)/4)   # eta(D_a) = zeta_H(0,a) - zeta_H(0,1-a)
eta34 = zeta(0, mpf(3)/4) - zeta(0, mpf(1)/4)
check("B10 eta(D_{1/4}) == +1/2, eta(D_{3/4}) == -1/2  (rational; FTD-0341 C1)",
      close(eta14, mpf(1)/2) and close(eta34, -mpf(1)/2))
check("B11 zeta_H(0, a) == 1/2 - a at a = 1/4, 3/4  (Bernoulli value)",
      close(zeta(0, mpf(1)/4), mpf(1)/4) and close(zeta(0, mpf(3)/4), -mpf(1)/4))
check("B12 AGM(1, sqrt2) == 2 sqrt(pi)/G* == 2 w^2 s^(-2)  (FTD-0327/0341 C4)",
      close(agm(1, sqrt(mpf(2))), 2*W**2/S**2))
