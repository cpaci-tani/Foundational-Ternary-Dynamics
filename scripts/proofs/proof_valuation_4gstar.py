# --------------------------------------- D. hull split and odd multiplicity
print("\nD. Hull level: t = s^2 splits (4t-1); delta^2 has odd multiplicity")
split = sp.factor(sp.expand((4*t - 1).subs(t, ssym**2)))
check("D1 4t-1 == (2s-1)(2s+1) under t = s^2 (the native sqrt(G*) line SPLITS the prime)",
      sp.expand(split - (2*ssym - 1)*(2*ssym + 1)) == 0)
d2 = sp.expand((t*(4*t - 1)).subs(t, ssym**2))
check("D2 delta^2 == 4s^4 - s^2 == s^2 (2s-1)(2s+1)",
      sp.expand(d2 - (4*ssym**4 - ssym**2)) == 0
      and sp.expand(d2 - ssym**2*(2*ssym - 1)*(2*ssym + 1)) == 0)
fl2 = sp.factor_list(sp.Poly(d2, ssym))
mults = {}
for f, m in fl2[1]:
    mults[sp.expand(f.as_expr())] = m
check("D3 multiplicities: (s)^2 (even), (2s-1)^1 and (2s+1)^1 (both ODD)",
      mults.get(ssym) == 2 and
      (mults.get(2*ssym - 1) == 1 or mults.get(ssym - sp.Rational(1, 2)) == 1) and
      (mults.get(2*ssym + 1) == 1 or mults.get(ssym + sp.Rational(1, 2)) == 1))
p_irr = sp.Poly(y**2 - d2, y, ssym)
check("D4 y^2 - delta^2 irreducible over Q[y, s]",
      len(sp.factor_list(p_irr)[1]) == 1 and sp.factor_list(p_irr)[1][0][1] == 1)
f_i = sp.factor(y**2 - d2, extension=[sp.I])
f_r2 = sp.factor(y**2 - d2, extension=[sp.sqrt(2)])
f_big = sp.factor(y**2 - d2, extension=[sp.I, sp.root(2, 4)])
def still_quadratic_in_y(e):
    fl_ = sp.factor_list(e)
    return len(fl_[1]) == 1 and fl_[1][0][1] == 1 and sp.degree(fl_[1][0][0], y) == 2
check("D5 y^2 - delta^2 stays irreducible over Q(i), Q(sqrt2), Q(i, 2^(1/4))",
      still_quadratic_in_y(f_i) and still_quadratic_in_y(f_r2) and still_quadratic_in_y(f_big))
check("D6 y^2 - t(4t-1) irreducible over Q[y, t, u] (F-level, matches FTD-0244 Lemma 2)",
      len(sp.factor_list(sp.Poly(y**2 - t*(4*t-1), y, t, u))[1]) == 1)
# Galois blindness: Tr and Det are delta-free; delta -> -delta swaps the roots
