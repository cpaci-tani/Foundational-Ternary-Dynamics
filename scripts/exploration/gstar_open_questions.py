# Compute the q-series values for sanity
q = exp(-2 * pi)


def sigma_k(n, k):
    """Sum of k-th powers of divisors of n."""
    s = mpf(0)
    for d in range(1, n + 1):
        if n % d == 0:
            s += d ** k
    return s


def eisenstein_qseries(k_weight, n_terms=80):
    """Compute E_k(i) via q-series. k_weight is the modular weight."""
    coef = {4: 240, 6: -504, 8: 480, 10: -264, 12: 65520 / mpf(691), 14: -24}
    sigma_exp = {4: 3, 6: 5, 8: 7, 10: 9, 12: 11, 14: 13}
    if k_weight not in coef:
        raise ValueError(f"Weight {k_weight} not supported")
    c = coef[k_weight]
    se = sigma_exp[k_weight]
    val = mpf(1)
    for n in range(1, n_terms):
        val += c * sigma_k(n, se) * q ** n
    return val


# Eisenstein series at tau = i: closed forms vs q-series
